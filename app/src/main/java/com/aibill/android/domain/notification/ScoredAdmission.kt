package com.aibill.android.domain.notification

/**
 * 评分窗口 + 跨渠道判重 module：独占「同金额候选的时间窗择优、跨渠道 60s 判重」这一条策略。
 *
 * ## 它压的是什么
 *
 * 同一笔交易会在几秒内从多个渠道各来一条（NLS 的短确认、A11Y 的支付结果页、
 * 银行的短信）。它们的金额相同，但信息完整度不同——评分窗口在 10s 内收集同金额候选，
 * 取信息最全的那条入账，其余的只是「同一笔的另一个视图」。
 *
 * ## 两条边界（都是产品语义，不要顺手改）
 *
 * - **同渠道同包名同金额 = 两笔真交易**（10s 内两杯 ¥15 咖啡）：不合并，前一笔立即
 *   提交、新交易开新窗口。同一条交易的重复通知更早会被预筛的内容去重 / DB 1s 去重拦掉。
 * - **跨渠道同金额 60s 内只留最优**：窗口到期后仍会查内存与 DB 两道，命中即丢弃。
 *   窗口外的第二条是「另一笔同金额消费」，按新交易处理。
 *
 * ## 为什么窗口产出用回调而不是返回值
 *
 * 窗口是**异步**的：调用方交出候选后立即返回（通知处理不该被 10s 窗口阻塞），
 * 产出在窗口到期时才发生。因此 [submit] 注册的是产出回调，由 module 用它自己的
 * 协程与时间轴触发——时间常数（10s / 60s / 5s 的清理）全部收在本 module。
 */
interface ScoredAdmission {

    /**
     * 交出一个候选，并注册本窗口的产出回调。
     *
     * 10s 窗口到期（或同来源同金额把前一笔立即提交）时，module 以「窗口内最优、
     * 且通过跨渠道判重」的那个候选回调一次 [onAdmitted]。
     * 未被选中的候选、被判为重复的候选都不回调——调用方不必知道判重细节。
     *
     * 非 suspend：本方法只登记状态，真正的等待与提交在 module 自己的协程里。
     */
    fun submit(candidate: ParsedTransaction, onAdmitted: suspend (ParsedTransaction) -> Unit)
}
